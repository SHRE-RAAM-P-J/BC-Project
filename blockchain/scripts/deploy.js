const { ethers, network } = require("hardhat");
const fs = require("fs");
const path = require("path");

async function main() {
  console.log("--------------------------------------------------");
  console.log(`Starting MediChain deployment on network: '${network.name}'...`);

  const [deployer] = await ethers.getSigners();
  console.log(`Deploying with account: ${deployer.address}`);
  const balance = await ethers.provider.getBalance(deployer.address);
  console.log(`Account balance: ${ethers.formatEther(balance)} ETH`);

  // 1. Deploy MediChain contract
  const MediChainFactory = await ethers.getContractFactory("MediChain");
  const mediChain = await MediChainFactory.deploy();
  await mediChain.waitForDeployment();

  const contractAddress = await mediChain.getAddress();
  console.log(`MediChain contract deployed to: ${contractAddress}`);

  // 2. Register initial seed batch to verify active write functionality
  const seedBatchId = "MC-2024-8849";
  const seedMedicine = "Paxlovid";
  const seedQuantity = 12500n;
  const now = Math.floor(Date.now() / 1000);
  const seedMfgDate = BigInt(now - 86400 * 45);
  const seedExpDate = BigInt(now + 86400 * 365 * 2);

  console.log(`Registering initial seed batch '${seedBatchId}' (${seedMedicine})...`);
  const registerTx = await mediChain.registerBatch(
    seedBatchId,
    seedMedicine,
    seedQuantity,
    seedMfgDate,
    seedExpDate
  );
  await registerTx.wait();
  console.log(`Seed batch '${seedBatchId}' successfully registered in block.`);

  // 3. Read Artifacts & ABI
  const artifactPath = path.join(
    __dirname,
    "../artifacts/contracts/MediChain.sol/MediChain.json"
  );

  if (!fs.existsSync(artifactPath)) {
    throw new Error(`Artifact file not found at ${artifactPath}. Please run 'npm run compile' first.`);
  }

  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));

  const deploymentData = {
    network: network.name,
    chainId: network.config.chainId || 31337,
    address: contractAddress,
    deployer: deployer.address,
    deployedAt: new Date().toISOString(),
    abi: artifact.abi,
  };

  // 4. Save to blockchain directory
  const localOutputPath = path.join(__dirname, "../deployed-contract.json");
  fs.writeFileSync(localOutputPath, JSON.stringify(deploymentData, null, 2), "utf8");
  console.log(`Saved deployment info to: ${localOutputPath}`);

  // 5. Export to frontend contracts directory
  const frontendContractsDir = path.resolve(__dirname, "../../frontend/src/contracts");
  if (!fs.existsSync(frontendContractsDir)) {
    fs.mkdirSync(frontendContractsDir, { recursive: true });
  }

  const frontendJsonPath = path.join(frontendContractsDir, "MediChain.json");
  fs.writeFileSync(frontendJsonPath, JSON.stringify(deploymentData, null, 2), "utf8");
  console.log(`Exported contract JSON to: ${frontendJsonPath}`);

  // Also create a TypeScript helper index.ts
  const frontendTsPath = path.join(frontendContractsDir, "index.ts");
  const tsContent = `// Auto-generated by blockchain/scripts/deploy.js
// Do not edit manually. Re-run deployment script to regenerate.
import contractData from './MediChain.json';

export const MEDICHAIN_CONTRACT_ADDRESS = "${contractAddress}";
export const MEDICHAIN_CHAIN_ID = ${network.config.chainId || 31337};
export const MEDICHAIN_ABI = contractData.abi;
export const MEDICHAIN_DEPLOYED_AT = "${deploymentData.deployedAt}";
export default contractData;
`;
  fs.writeFileSync(frontendTsPath, tsContent, "utf8");
  console.log(`Exported TypeScript bindings to: ${frontendTsPath}`);

  console.log("--------------------------------------------------");
  console.log("Deployment and export completed successfully!");
}

main()
  .then(() => process.exit(0))
  .catch((error) => {
    console.error("Deployment failed:", error);
    process.exit(1);
  });
